const QC_FISHING_DEFAULT = 'https://www.quebec.ca/tourisme-et-loisirs/activites-sportives-et-de-plein-air/peche-et-chasse/peche';

// Process each data file
const categories = ['skiing', 'camping', 'hiking', 'hunting', 'kayaking', 'fishing'];

categories.forEach(cat => {
  const filePath = `data/${cat}.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  let updated = 0;
  data.spots.forEach(spot => {
    const url = websites[cat]?.[spot.slug];
    if (url) {
      spot.website = url;
      updated++;
    } else if (cat === 'fishing' && spot.province === 'Quebec' && !spot.website) {
      // Quebec lakes default to government fishing page
      spot.website = QC_FISHING_DEFAULT;
      updated++;
    } else {
      spot.website = '';
    }
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2));
  console.log(`${cat}: Updated ${updated}/${data.spots.length} spots with website URLs`);
});

