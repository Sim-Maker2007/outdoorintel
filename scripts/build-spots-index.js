#!/usr/bin/env node
/* Builds a compact, server-side grounding index for Scout (the AI planner).
 * One entry per spot with just what the model needs to select and explain a
 * pick. Emitted as an ESM module so Vercel bundles it with the function
 * (no fs paths, no JSON import assertions). Never shipped to the browser. */
const fs = require('fs');
const path = require('path');

const CATS = ['fishing', 'hunting', 'camping', 'kayaking', 'skiing', 'hiking'];

function firstSentence(text) {
  if (!text) return '';
  var t = String(text).replace(/\s+/g, ' ').trim();
  var m = t.match(/^(.{20,180}?[.!?])\s/);
  return (m ? m[1] : t.slice(0, 160)).trim();
}

const out = [];
for (const cat of CATS) {
  const file = path.join('data', cat + '.json');
  if (!fs.existsSync(file)) continue;
  const d = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const s of (d.spots || [])) {
    const species = s.primary_species || s.primary_game || s.features || [];
    out.push({
      s: s.slug,
      c: cat,
      n: s.name,
      p: s.province || '',
      lat: s.coordinates && s.coordinates.lat != null ? Number(s.coordinates.lat) : null,
      lng: s.coordinates && s.coordinates.lng != null ? Number(s.coordinates.lng) : null,
      sp: Array.isArray(species) ? species.slice(0, 6) : [],
      lvl: s.scout_level || '',
      blurb: firstSentence(s.description)
    });
  }
}

const header = '/* AUTO-GENERATED by scripts/build-spots-index.js — do not edit by hand.\n' +
  ' * Compact grounding index for Scout. ' + out.length + ' spots. */\n';
fs.mkdirSync('api/_data', { recursive: true });
fs.writeFileSync('api/_data/spots-index.js', header + 'export default ' + JSON.stringify(out) + ';\n');
console.log('Wrote api/_data/spots-index.js with ' + out.length + ' spots (' +
  (fs.statSync('api/_data/spots-index.js').size / 1024).toFixed(0) + ' KB)');
