#!/usr/bin/env node
// Bundle data/regulations/*.json into api/_data/regs-index.js so the
// serverless Answer Layer endpoint ships with its data (same pattern as
// scripts/build-spots-index.js -> api/_data/spots-index.js).
//
// Keys: Québec uses zone_id ("10", "12"). Ontario uses zone_key ("ON-12").
// An ON document indexed as "12" fails the build.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { regulationKey, assertUniqueRegulationKeys } from '../../src/lib/regsLookup.mjs';

const REPO = process.cwd();
const dir = join(REPO, 'data', 'regulations');
const zones = {};
for (const f of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
  const doc = JSON.parse(readFileSync(join(dir, f), 'utf-8'));
  const key = regulationKey(doc);
  if (Object.prototype.hasOwnProperty.call(zones, key)) {
    throw new Error(`duplicate regulation key "${key}" from ${f}`);
  }
  if (doc.jurisdiction === 'ON' && (/^\d+$/.test(key) || key === String(doc.zone_id))) {
    throw new Error(`ON document ${f} would be indexed as "${key}" — refuse (Québec collision)`);
  }
  if (doc.jurisdiction === 'ON' && doc.jurisdiction !== 'ON') {
    throw new Error(`ON document ${f} missing jurisdiction ON`);
  }
  if (doc.jurisdiction === 'ON' && !/^ON-\d+$/.test(key)) {
    throw new Error(`ON document ${f} key must be ON-{{fmz}}, got "${key}"`);
  }
  zones[key] = doc;
}
assertUniqueRegulationKeys(zones);
const out = `// GENERATED by scripts/regs/build-regs-index.mjs — do not edit.\nexport const REGS = ${JSON.stringify(zones)};\n`;
writeFileSync(join(REPO, 'api', '_data', 'regs-index.js'), out);
console.log(`regs-index: keys ${Object.keys(zones).join(', ')} -> api/_data/regs-index.js`);
