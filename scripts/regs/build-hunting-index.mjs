#!/usr/bin/env node
// Bundle data/hunting/*.json into api/_data/hunting-index.js.
// Separate from fishing regs-index. Keys are QC-H-10W, never "12" or "ON-12".
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { huntingKey } from '../../src/lib/huntLookup.mjs';

const REPO = process.cwd();
const dir = join(REPO, 'data', 'hunting');
const hunt = {};
for (const f of readdirSync(dir).filter(x => x.endsWith('.json')).sort()) {
  const doc = JSON.parse(readFileSync(join(dir, f), 'utf-8'));
  if (doc.activity !== 'hunting') {
    throw new Error(`${f} is not activity hunting`);
  }
  const key = huntingKey(doc);
  if (!key.startsWith('QC-H-') && !key.startsWith('ON-H-')) {
    throw new Error(`${f} key "${key}" is not a hunting namespace`);
  }
  if (key === '12' || key === 'ON-12' || key === 'ON-H-12') {
    throw new Error(`${f} refuses hunting key ${key} (fishing collision / Rainy River WMU 12)`);
  }
  if (Object.prototype.hasOwnProperty.call(hunt, key)) {
    throw new Error(`duplicate hunting key "${key}" from ${f}`);
  }
  hunt[key] = doc;
}
mkdirSync(join(REPO, 'api', '_data'), { recursive: true });
const out = `// GENERATED by scripts/regs/build-hunting-index.mjs — do not edit.\nexport const HUNTING = ${JSON.stringify(hunt)};\n`;
writeFileSync(join(REPO, 'api', '_data', 'hunting-index.js'), out);
console.log(`hunting-index: keys ${Object.keys(hunt).join(', ')} -> api/_data/hunting-index.js`);
